package Day4;

public class Conditions {
    public static void main(String[] args) {
        int x = 5;
        int y = 5;

        if (x > y) {
            System.out.println("Result 1: X > Y");
        } else if ( x == y) {
            System.out.println("Result 2: X = Y");
        }
        else {
            System.out.println("Result 3: X < Y");
        }
    }
}
